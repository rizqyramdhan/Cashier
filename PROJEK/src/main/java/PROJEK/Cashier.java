    private void tambahbarangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tambahbarangActionPerformed
        // TODO add your handling code here:
        String nama = namabarang.getText();
        String harga = hargabarang.getText();
        int hargasatuan = Integer.parseInt(harga);
        int subtotal = hargasatuan * jumlah;
        
        daftarnama.add(nama);
        daftarjumlah.add(jumlah);
        daftarharga.add(hargasatuan);
        daftarsubtotal.add(subtotal);
        
        total = total + subtotal;
        totalbayar.setText("Rp " + total);
        
        String barangbaru = nama + "   Jumlah: " + jumlah + "   Harga: " + harga;
        barang.add(barangbaru);
        
        total = 0;
        for (int i = 0; i < daftarsubtotal.size(); i++) {
            total = total + daftarsubtotal.get(i);
        }
        
        String[] data = new String[barang.size()];
        for (int i = 0; i < barang.size(); i++) {
            data[i] = barang.get(i);
        }
        daftarbarang.setListData(data);
        
        namabarang.setText("");
        hargabarang.setText("");
        jumlah = 1;
        jumlahbarang.setText("" + jumlah);
    }//GEN-LAST:event_tambahbarangActionPerformed

    private void hapusbarangActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_hapusbarangActionPerformed
        // TODO add your handling code here:
        int indexdipilih = daftarbarang.getSelectedIndex();
        
        
        daftarnama.remove(indexdipilih);
        daftarjumlah.remove(indexdipilih);
        daftarharga.remove(indexdipilih);
        daftarsubtotal.remove(indexdipilih);
        barang.remove(indexdipilih);
        
        total = 0;
        for (int i = 0; i < daftarsubtotal.size();i ++) {
            total = total + daftarsubtotal.get(i);
        }
        totalbayar.setText("Rp " + total);
        
        String[] data = new String[barang.size()];
        for (int i = 0; i < barang.size(); i++) {
            data[i] = barang.get(i);
        }
        daftarbarang.setListData(data);
    }//GEN-LAST:event_hapusbarangActionPerformed

