    private void cetakstrukActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cetakstrukActionPerformed
        // TODO add your handling code here:
        String uang = uangtunai.getText();
        if (uang.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Masukkan uang tunai terlebih dahulu");
        }
        
        int tunai = Integer.parseInt(uangtunai.getText());
        
        if (tunai < total) {
            kembalian.setText("Uang kurang");
            JOptionPane.showMessageDialog(this, "Uang yang dimasukkan kurang!");
        } else {
            int kembali = tunai - total;
            kembalian.setText("Rp " + kembali);
            
            String teks = "=====================================\n";
            teks = teks + "                         REYFAN STORE\n";
            teks = teks + "=====================================\n";
            for (int i = 0; i < daftarnama.size(); i++) {
                teks = teks + " " + daftarnama.get(i) + "\n";
                teks = teks + "      " + daftarjumlah.get(i) + " x Rp " + daftarharga.get(i) + " = Rp " + daftarsubtotal.get(i) + "\n";
            }
            
            teks = teks + "-----------------------------------------------------------------\n";
            teks = teks + "TOTAL                Rp " + total + "\n";
            teks = teks + "TUNAI                 Rp " + tunai + "\n";
            teks = teks + "KEMBALIAN        Rp " + kembali + "\n";
            teks = teks + "=====================================\n";
            teks = teks + "                 Terimakasih telah berbelanja     \n";
            teks = teks + "=====================================\n";
            
            JOptionPane.showMessageDialog(this, teks);
        }
    }//GEN-LAST:event_cetakstrukActionPerformed

